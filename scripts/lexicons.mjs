#!/usr/bin/env node
// Vendors hikeratlas/atproto-lexicon's lexicons at the commit in
// lexicons/REF, and generates src/lexicons.ts from them: the documents (for
// validation with @atproto/lexicon) and TypeScript types for their records
// and objects.
//
//     npm run lexicons              # regenerate from lexicons/REF
//     npm run lexicons -- <ref>     # move to a branch, tag or full commit first
//
// The JSON is checked in, so builds need no network; CI checks that
// src/lexicons.ts matches it.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'lexicons');
const refFile = path.join(dir, 'REF');
const REPO = 'https://github.com/hikeratlas/atproto-lexicon';

const want = process.argv[2];
if (want) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lexicons-'));
  const git = (...a) => execFileSync('git', ['-C', tmp, ...a], { stdio: ['ignore', 'pipe', 'inherit'] }).toString().trim();
  git('init', '-q');
  git('fetch', '-q', '--depth', '1', REPO, want);
  const sha = git('rev-parse', 'FETCH_HEAD');
  git('checkout', '-q', 'FETCH_HEAD');
  for (const f of fs.readdirSync(dir)) if (f !== 'REF') fs.rmSync(path.join(dir, f), { recursive: true });
  fs.cpSync(path.join(tmp, 'lexicons'), dir, { recursive: true });
  fs.writeFileSync(refFile, `${sha}\n`);
  fs.rmSync(tmp, { recursive: true });
}

const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (f.name.endsWith('.json')) files.push(p);
  }
})(dir);
const docs = files.map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
const byId = new Map(docs.map((d) => [d.id, d]));

// atproto's own lexicons that ours refer to. They aren't in
// hikeratlas/atproto-lexicon, but validation needs them: without
// com.atproto.repo.strongRef, every review with a track failed
// assertValidRecord ("Lexicon not found") and was skipped. Copied from
// bluesky-social/atproto's lexicons/com/atproto/repo/strongRef.json.
const STANDARD = [
  {
    lexicon: 1,
    id: 'com.atproto.repo.strongRef',
    description: 'A URI with a content-hash fingerprint.',
    defs: {
      main: {
        type: 'object',
        required: ['uri', 'cid'],
        properties: {
          uri: { type: 'string', format: 'at-uri' },
          cid: { type: 'string', format: 'cid' },
        },
      },
    },
  },
];
const known = new Map([...STANDARD, ...docs].map((d) => [d.id, d]));

// Every ref must resolve, here or in STANDARD: a missing one makes each
// record that uses it fail validation, quietly (it's skipped as invalid).
function refs(v, id) {
  if (Array.isArray(v)) return v.forEach((x) => refs(x, id));
  if (!v || typeof v !== 'object') return;
  for (const r of v.type === 'ref' ? [v.ref] : v.type === 'union' ? v.refs : []) {
    const [nsid, name] = r.split('#');
    const target = known.get(nsid || id);
    if (!target?.defs[name || 'main']) throw new Error(`${id}: ${r} isn't defined (add it to STANDARD if it's atproto's)`);
  }
  for (const x of Object.values(v)) refs(x, id);
}
for (const d of docs) refs(d.defs, d.id);

// A def's TypeScript name: com.hikeratlas.temp.review -> Review,
// com.hikeratlas.temp.defs#photo -> Photo, ...actor.profile#units -> ProfileUnits.
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
function typeName(id, name) {
  const last = pascal(id.split('.').pop());
  if (last === 'Defs') return pascal(name);
  return name === 'main' ? last : last + pascal(name);
}

function tsType(schema, id) {
  switch (schema.type) {
    case 'string': return schema.knownValues ? `${schema.knownValues.map((v) => JSON.stringify(v)).join(' | ')} | (string & {})` : 'string';
    case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'blob': return 'BlobRef';
    case 'unknown': return 'unknown';
    case 'array': { const t = tsType(schema.items, id); return /[ |]/.test(t) ? `(${t})[]` : `${t}[]`; }
    case 'ref': {
      const [nsid, name] = schema.ref.split('#');
      if (nsid === 'com.atproto.repo.strongRef') return 'StrongRef';
      const target = nsid || id;
      const def = byId.get(target)?.defs[name || 'main'];
      if (def && def.type === 'string') return tsType(def, target);
      return typeName(target, name || 'main');
    }
    case 'object': return objectType(schema, id);
    default: throw new Error(`${id}: no TypeScript type for ${schema.type}`);
  }
}

function objectType(schema, id, indent = '') {
  const req = new Set(schema.required ?? []);
  const lines = Object.entries(schema.properties ?? {}).map(([k, v]) =>
    `${indent}  ${k}${req.has(k) ? '' : '?'}: ${tsType(v, id)};`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}

let out = `// Generated by scripts/lexicons.mjs from hikeratlas/atproto-lexicon at
// ${fs.readFileSync(refFile, 'utf8').trim()} (lexicons/REF). Don't edit: run npm run lexicons.
import type { LexiconDoc } from '@atproto/lexicon';

export const LEXICON_REF = ${JSON.stringify(fs.readFileSync(refFile, 'utf8').trim())};

export interface BlobRef { $type: 'blob'; ref: { $link: string }; mimeType: string; size: number }
export interface StrongRef { uri: string; cid: string }

`;
const collections = [];
const queries = [];
for (const d of docs) {
  for (const [name, def] of Object.entries(d.defs)) {
    if (def.type === 'record') {
      collections.push([typeName(d.id, name), d.id]);
      out += `// ${d.id} (record key: ${def.key})\nexport interface ${typeName(d.id, name)} ${objectType(def.record, d.id)}\n\n`;
    } else if (def.type === 'object') {
      out += `export interface ${typeName(d.id, name)} ${objectType(def, d.id)}\n\n`;
    } else if (def.type === 'query') {
      const t = typeName(d.id, name);
      queries.push([t, d.id]);
      out += `// ${d.id} (query)\nexport interface ${t}Params ${objectType(def.parameters ?? {}, d.id)}\n`;
      out += `export interface ${t}Output ${objectType(def.output.schema, d.id)}\n\n`;
    }
  }
}
out += `// Record collections.\nexport const NSID = {\n${collections.map(([t, id]) => `  ${t}: ${JSON.stringify(id)},`).join('\n')}\n} as const;\n\n`;
out += `// Queries.\nexport const QUERY = {\n${queries.map(([t, id]) => `  ${t}: ${JSON.stringify(id)},`).join('\n')}\n} as const;\n\n`;
out += `export const LEXICONS = ${JSON.stringify([...docs, ...STANDARD], null, 2)} as unknown as LexiconDoc[];\n`;
fs.writeFileSync(path.join(root, 'src', 'lexicons.ts'), out);
console.log(`${docs.length} lexicons at ${fs.readFileSync(refFile, 'utf8').trim()} -> src/lexicons.ts`);
